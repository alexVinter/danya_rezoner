export interface ServiceItem {
  id: string;
  slug: string;
  title: string;
  shortDesc?: string;
  forWhom?: string;
  whatsInside: string[];
  price?: string;
  priceNote?: string;
  minBudget?: string;
  timeline?: string;
  tariffs?: Array<{ name: string; price: string; desc: string }>;
  [key: string]: any;
}

export interface ServiceHero {
  chip?: string;
  h1: string;
  h1Mark: string;
  lead: string;
  audience: string;
  price: string;
  priceNote: string;
  buttonText: string;
  anchor: { text: string; target: string };
  illustration: string;
  illustrationClass: string;
}

export interface ServiceQuoteBlock {
  type: 'quote';
  title: string;
  quote: string;
  caption: string;
  paragraph?: string;
}

export interface ServiceRowsBlock {
  type: 'rows';
  id?: string;
  title: string;
  items: Array<{ title: string; text: string }>;
  footnote?: string;
}

export interface ServiceStepItem {
  num: string;
  chip?: string;
  title: string;
  text: string;
}

export interface ServiceStepsBlock {
  type: 'steps';
  id?: string;
  title: string;
  items: ServiceStepItem[];
}

export interface ServicePriceRow {
  name: string;
  text: string;
  price: string;
  note?: string;
}

export interface ServicePricesBlock {
  type: 'prices';
  title: string;
  items: ServicePriceRow[];
  footnote: string;
}

export interface ServicePricePlateBlock {
  type: 'pricePlate';
  title: string;
  text: string;
  price: string;
  priceNote: string;
  buttonText: string;
}

export interface ServiceCaseLinkBlock {
  type: 'caseLink';
  title: string;
  caseSlug: string;
  metric: string;
  heading: string;
  tags: string;
}

export interface ServiceCaseCardsBlock {
  type: 'caseCards';
  title: string;
  cards: Array<{
    caseSlug: string;
    metric: string;
    heading: string;
    desc: string;
  }>;
}

export interface ServiceFlowBlock {
  type: 'flow';
  id?: string;
  title: string;
  steps: Array<{ title: string; text: string; isHighlight?: boolean }>;
  caption: string;
}

export interface ServiceFormatsBlock {
  type: 'formats';
  id?: string;
  title: string;
  cards: Array<{
    title: string;
    price: string;
    paragraphs?: string[];
    bullets?: string[];
  }>;
}

export interface ServiceNoteBlock {
  type: 'note';
  title: string;
  paragraphs: string[];
  caseTeaser?: {
    caseSlug: string;
    metric: string;
    heading: string;
  };
}

export type ServiceBlock =
  | ServiceQuoteBlock
  | ServiceRowsBlock
  | ServiceStepsBlock
  | ServicePricesBlock
  | ServicePricePlateBlock
  | ServiceCaseLinkBlock
  | ServiceCaseCardsBlock
  | ServiceFlowBlock
  | ServiceFormatsBlock
  | ServiceNoteBlock;

export interface ServiceFaq {
  title?: string;
  subtitle?: string;
  items: Array<{ question: string; answer: string }>;
}

export interface ServiceData {
  slug: string;
  title: string; // for document.title
  description: string; // for meta description
  breadcrumb: string;
  hero: ServiceHero;
  blocks: ServiceBlock[];
  faq?: ServiceFaq;
  cta: {
    title: string;
    titleMark: string;
    text: string;
  };
}

